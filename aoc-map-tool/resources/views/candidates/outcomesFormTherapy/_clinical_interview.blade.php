<script>
    $.validator.addClassRules("required-field", {
        required: true,
    });

    validation = {
        onfocusout: false,
        ignore: ':disabled',
        invalidHandler: function (form, validator) {
            if (validator.numberOfInvalids()) {
                var $firstInvalid = $(validator.errorList[0].element);
                var $pane = $firstInvalid.closest('.tab-pane');

                if ($pane.length && !$pane.hasClass('active')) {
                    $('a[href="#' + $pane.attr('id') + '"]').tab('show');
                    setTimeout(function () { $firstInvalid.focus(); }, 150);
                } else {
                    $firstInvalid.focus();
                }
            }
        },
        errorPlacement: function (error, element) {
        }
    };

    $('#jobViteOutcomeForm').validate(validation);

    initCharsLimit(document);
</script>
